import http from 'node:http';
import https from 'node:https';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { selectApp, entryHtml } from './apps.mjs';
const root = fileURLToPath(new URL('..', import.meta.url));
const app = selectApp();
const backend = new URL(process.env[app.backendEnv] || app.backend);
if (!['http:', 'https:'].includes(backend.protocol)) throw new Error(`${app.backendEnv} must use http(s):`);
const appRoots = ['apps', 'ui', 'themes'].map(layer => path.join(root, 'src', layer, app.name));
const themeRoot = appRoots[0];
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json', '.wasm': 'application/wasm', '.woff2': 'font/woff2', '.ico': 'image/x-icon', '.webp': 'image/webp', '.txt': 'text/plain; charset=utf-8' };
function proxy(req, res) {
  const headers = { ...req.headers, host: backend.host };
  // Preserve same-origin checks when the development origin differs from upstream.
  if (headers.origin === `http://${req.headers.host}`) headers.origin = backend.origin;
  const upstream = (backend.protocol === 'https:' ? https : http).request(new URL(req.url, backend), { method: req.method, headers }, reply => {
    res.writeHead(reply.statusCode, reply.headers); reply.pipe(res); reply.on('error', () => res.destroy());
  });
  upstream.on('error', () => {
    if (res.headersSent) return res.destroy();
    res.writeHead(502, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ error: `无法连接 ${app.name} 后端：${backend.origin}` }));
  });
  res.on('close', () => upstream.destroy()); req.pipe(upstream);
}
const server = http.createServer(async (req, res) => {
  try {
    const url = new URL(req.url, 'http://localhost');
    const pathname = decodeURIComponent(url.pathname);
    if (pathname === '/api' || pathname.startsWith('/api/') || pathname === '/auth' || pathname.startsWith('/auth/')) return proxy(req, res);
    // Localized SEO articles are generated by ipqcheck's original backend.
    if (app.name === 'ipqcheck' && (/^\/methodology\/[^.]+$/.test(pathname) || (/^\/guides\//.test(pathname) && !path.extname(pathname)))) return proxy(req, res);
    const isSource = pathname.startsWith('/src/');
    const allowed = isSource ? path.join(root, 'src') : themeRoot;
    const relative = app.name === 'finpri' && pathname.startsWith('/console/') ? pathname.slice('/console'.length) : pathname;
    let file = isSource ? path.resolve(root, '.' + pathname) : path.resolve(themeRoot, '.' + (relative === '/' || relative === '/console' ? '/index.html' : relative));
    if (!file.startsWith(allowed + path.sep)) { res.writeHead(403); return res.end(); }
    try {
      if (!isSource) {
        for (const base of appRoots) {
          const candidate = path.resolve(base, '.' + (relative === '/' || relative === '/console' ? '/index.html' : relative));
          if (!candidate.startsWith(base + path.sep)) continue;
          try { await stat(candidate); file = candidate; break; } catch {}
        }
      }
      if ((await stat(file)).isDirectory()) file = path.join(file, 'index.html');
    }
    catch {
      if (app.name === 'ipqcheck' && /^\/(?:browser-fingerprint|(?:gpt|claude|gemini|grok|kiro|copilot)-check|(?:youtube|tiktok|x|instagram)-ip-check)\/?$/.test(pathname)) file = path.join(themeRoot, 'index.html');
      else throw new Error('Not found');
    }
    let content = await readFile(file);
    if (file.endsWith('.html')) {
      content = entryHtml(content.toString(), app);
      if (app.name === 'ipqcheck' && !/src="\/src\/apps\/ipqcheck\/entry.js"/.test(content) && content.includes('/main.js')) content = content.replace('src="/main.js"', 'src="/src/apps/ipqcheck/entry.js"');
    }
    res.writeHead(200, { 'content-type': mime[path.extname(file)] || 'application/octet-stream', 'cache-control': 'no-store' }); res.end(content);
  } catch { res.writeHead(404); res.end('Not found'); }
});
server.listen(Number(process.env.PORT || 4173), process.env.HOST || '127.0.0.1', () => {
  console.log(`Lily UI: http://${process.env.HOST || '127.0.0.1'}:${server.address().port} [${app.name}] → ${backend.origin}`);
});
