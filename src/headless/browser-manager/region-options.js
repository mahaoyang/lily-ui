export function countryItems(current = '') {
  const zh = new Intl.DisplayNames(['zh-CN'], { type: 'region' })
  const en = new Intl.DisplayNames(['en'], { type: 'region' })
  const codes = new Set(CITIES.map(row => row[0]))
  if (/^[A-Z]{2}$/.test(current)) codes.add(current)
  return [{ value: '', label: '请选择国家或地区' }, ...[...codes].map(value => ({ value, label: `${zh.of(value)} · ${en.of(value)} · ${value}` })).sort((a, b) => a.label.localeCompare(b.label, 'zh-CN'))]
}

export function cityItems(country, current = '') {
  const items = CITIES.filter(row => row[0] === country).map(([, value, timezone, zh]) => ({ value, timezone, label: zh ? `${zh} · ${value}` : value }))
  if (current && !items.some(item => item.value === current)) items.unshift({ value: current, label: `${current}（已保存）` })
  return [{ value: '', label: country ? '请选择主要城市（可选）' : '请先选择国家或地区' }, ...items]
}
