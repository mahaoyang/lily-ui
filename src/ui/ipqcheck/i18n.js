export function translateForLocale(locale, key) {
  return MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
}

export function normalizeLocale(locale) {
  const raw = String(locale || '').trim();
  if (!raw) return null;
  if (SUPPORTED_LOCALES.includes(raw)) return raw;
  const lower = raw.toLowerCase();
  const language = lower.split('-')[0];
  if (['en', 'ja', 'ko', 'fr', 'es', 'pt', 'de', 'ar'].includes(language)) return language;
  if (lower === 'zh' || lower.startsWith('zh-')) {
    // Back-compat for old stored values.
    if (lower === 'zh-cn') return 'zh-Hans';
    if (lower === 'zh-tw') return 'zh-Hant';

    // Use native script subtags when possible (avoid region abbreviations in UI/state).
    if (/(hant|hk|mo|tw)/i.test(raw)) return 'zh-Hant';
    if (/(hans|cn|sg)/i.test(raw)) return 'zh-Hans';
    return 'zh-Hans';
  }
  return null;
}

export function localeFromLanguages(languages = []) {
  for (const candidate of languages) {
    const locale = normalizeLocale(candidate);
    if (locale) return locale;
  }
  return null;
}

export function localeFromCountry(country) {
  const code = String(country || '').toUpperCase();
  const groups = {
    'zh-Hans': ['CN', 'SG'], 'zh-Hant': ['TW', 'HK', 'MO'],
    ja: ['JP'], ko: ['KR'], fr: ['FR', 'MC'], de: ['DE', 'AT', 'LI'],
    es: ['ES', 'MX', 'AR', 'BO', 'CL', 'CO', 'CR', 'CU', 'DO', 'EC', 'GT', 'HN', 'NI', 'PA', 'PE', 'PY', 'SV', 'UY', 'VE'],
    pt: ['PT', 'BR', 'AO', 'MZ', 'CV', 'GW', 'ST'],
    ar: ['AE', 'SA', 'EG', 'DZ', 'BH', 'IQ', 'JO', 'KW', 'LB', 'LY', 'MA', 'OM', 'PS', 'QA', 'SD', 'SY', 'TN', 'YE'],
  };
  return Object.entries(groups).find(([, countries]) => countries.includes(code))?.[0] ?? 'en';
}

export function localeFromRequest(headers = {}) {
  const candidates = String(headers['accept-language'] || '').split(',')
    .map((part, index) => {
      const [language, ...params] = part.trim().split(';');
      const quality = params.find((param) => param.trim().startsWith('q='));
      return { language, index, q: quality ? Number(quality.trim().slice(2)) : 1 };
    })
    .filter(({ q }) => Number.isFinite(q) && q > 0 && q <= 1)
    .sort((a, b) => b.q - a.q || a.index - b.index);
  return localeFromLanguages(candidates.map(({ language }) => language))
    ?? localeFromCountry(headers['cf-ipcountry'] ?? headers['x-vercel-ip-country']);
}

export function detectLocale() {
  const browser = globalThis.navigator;
  return localeFromLanguages([
    ...(Array.isArray(browser?.languages) ? browser.languages : []),
    browser?.language,
  ]) ?? normalizeLocale(globalThis.document?.documentElement?.lang) ?? 'en';
}

export function getStoredLocale() {
  try {
    return normalizeLocale(localStorage.getItem(STORAGE_KEY));
  } catch {
    return null;
  }
}

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale, { persist = true } = {}) {
  const normalized = normalizeLocale(locale) ?? 'en';
  currentLocale = normalized;
  try {
    if (persist) localStorage.setItem(STORAGE_KEY, normalized);
  } catch {
    // ignore
  }
  document.documentElement.lang = normalized;
  document.documentElement.dir = normalized === 'ar' ? 'rtl' : 'ltr';
}

